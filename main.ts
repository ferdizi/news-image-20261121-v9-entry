// ---------- TTF parsing (subset fonts embedded above) ----------
type Pt = { x: number; y: number; on: boolean };
type Contour = Pt[];
type Font = {
  upm: number; cmap: Map<number, number>; glyphs: number;
  loca: number[]; glyf: Uint8Array; hmtx: Uint8Array; numH: number; longLoca: boolean;
};
function u16(b: Uint8Array, o: number): number { return (b[o] << 8) | b[o + 1]; }
function i16(b: Uint8Array, o: number): number { const v = u16(b, o); return v >= 32768 ? v - 65536 : v; }
function u32(b: Uint8Array, o: number): number { return ((b[o] * 256 + b[o + 1]) * 256 + b[o + 2]) * 256 + b[o + 3]; }
function tableDir(b: Uint8Array): Map<string, { off: number; len: number }> {
  const m = new Map<string, { off: number; len: number }>();
  const n = u16(b, 4);
  for (let i = 0; i < n; i++) {
    const o = 12 + i * 16;
    const tag = String.fromCharCode(b[o], b[o + 1], b[o + 2], b[o + 3]);
    m.set(tag, { off: u32(b, o + 8), len: u32(b, o + 12) });
  }
  return m;
}
function parseFont(b64: string): Font {
  const raw = Buffer.from(b64.replace(/\s/g, ""), "base64");
  const b = new Uint8Array(raw.buffer, raw.byteOffset, raw.byteLength);
  const t = tableDir(b);
  const head = t.get("head")!; const maxp = t.get("maxp")!;
  const hhea = t.get("hhea")!; const hmtx = t.get("hmtx")!;
  const cmapT = t.get("cmap")!; const locaT = t.get("loca")!; const glyfT = t.get("glyf")!;
  const upm = u16(b, head.off + 18);
  const longLoca = i16(b, head.off + 50) === 1;
  const glyphs = u16(b, maxp.off + 4);
  const numH = u16(b, hhea.off + 34);
  const loca: number[] = [];
  for (let i = 0; i <= glyphs; i++) {
    loca.push(longLoca ? u32(b, locaT.off + i * 4) : u16(b, locaT.off + i * 2) * 2);
  }
  // cmap format 4: prefer platform 3 encoding 1, else 0
  let sub = -1;
  const nSub = u16(b, cmapT.off + 2);
  for (let i = 0; i < nSub; i++) {
    const p = u16(b, cmapT.off + 4 + i * 8); const e = u16(b, cmapT.off + 6 + i * 8);
    const o = u32(b, cmapT.off + 8 + i * 8);
    if (u16(b, cmapT.off + o) === 4 && (p === 3 && (e === 1 || e === 0))) { sub = cmapT.off + o; break; }
  }
  if (sub < 0) { // fallback: first format-4 subtable
    for (let i = 0; i < nSub; i++) {
      const o = u32(b, cmapT.off + 8 + i * 8);
      if (u16(b, cmapT.off + o) === 4) { sub = cmapT.off + o; break; }
    }
  }
  const cmap = new Map<number, number>();
  const segCount = u16(b, sub + 6) / 2;
  const endBase = sub + 14;
  const startBase = endBase + segCount * 2 + 2;
  const deltaBase = startBase + segCount * 2;
  const rangeBase = deltaBase + segCount * 2;
  for (let s = 0; s < segCount; s++) {
    const end = u16(b, endBase + s * 2); const start = u16(b, startBase + s * 2);
    const delta = i16(b, deltaBase + s * 2); const ro = u16(b, rangeBase + s * 2);
    for (let c = start; c <= end && c < 65535; c++) {
      let g = 0;
      if (ro === 0) g = (c + delta) & 0xffff;
      else {
        const gi = rangeBase + s * 2 + ro + (c - start) * 2;
        g = u16(b, gi); if (g !== 0) g = (g + delta) & 0xffff;
      }
      if (g !== 0) cmap.set(c, g);
    }
  }
  return {
    upm, cmap, glyphs, loca,
    glyf: b.slice(glyfT.off, glyfT.off + glyfT.len),
    hmtx: b.slice(hmtx.off, hmtx.off + hmtx.len), numH, longLoca,
  };
}
function advanceOf(f: Font, gid: number): number {
  const i = Math.min(gid, f.numH - 1);
  return u16(f.hmtx, i * 4);
}
// Read one glyph's contours in font units (y up), composites expanded.
function glyphContours(f: Font, gid: number, depth: number): Contour[] {
  if (depth > 3 || gid >= f.glyphs) return [];
  const start = f.loca[gid]; const end = f.loca[gid + 1];
  if (end <= start) return [];
  const g = f.glyf.subarray(start, end);
  const nC = i16(g, 0);
  if (nC >= 0) {
    const endPts: number[] = [];
    for (let i = 0; i < nC; i++) endPts.push(u16(g, 10 + i * 2));
    let p = 10 + nC * 2;
    const insLen = u16(g, p); p += 2 + insLen;
    const flags: number[] = [];
    const total = endPts.length ? endPts[endPts.length - 1] + 1 : 0;
    while (flags.length < total) {
      const fl = g[p++];
      flags.push(fl);
      if (fl & 0x08) { const rep = g[p++]; for (let i = 0; i < rep; i++) flags.push(fl); }
    }
    const xs: number[] = []; const ys: number[] = [];
    let x = 0;
    for (let i = 0; i < total; i++) {
      const fl = flags[i];
      if (fl & 0x02) { const d = g[p++]; x += (fl & 0x10) ? d : -d; }
      else if (!(fl & 0x10)) { x += i16(g, p); p += 2; }
      xs.push(x);
    }
    let y = 0;
    for (let i = 0; i < total; i++) {
      const fl = flags[i];
      if (fl & 0x04) { const d = g[p++]; y += (fl & 0x20) ? d : -d; }
      else if (!(fl & 0x20)) { y += i16(g, p); p += 2; }
      ys.push(y);
    }
    const out: Contour[] = [];
    let s0 = 0;
    for (const e of endPts) {
      const c: Contour = [];
      for (let i = s0; i <= e; i++) c.push({ x: xs[i], y: ys[i], on: (flags[i] & 0x01) === 1 });
      out.push(c); s0 = e + 1;
    }
    return out;
  }
  // composite glyph
  let p = 10; const out: Contour[] = [];
  for (;;) {
    const flags = u16(g, p); const comp = u16(g, p + 2); p += 4;
    let arg1 = 0; let arg2 = 0;
    if (flags & 0x0001) { arg1 = i16(g, p); arg2 = i16(g, p + 2); p += 4; }
    else { arg1 = g[p]; arg2 = g[p + 1]; p += 2; }
    let a = 1; let b2 = 0; let c2 = 0; let d = 1;
    if (flags & 0x0008) { a = i16(g, p) / 16384; d = a; p += 2; }
    else if (flags & 0x0080) { a = i16(g, p) / 16384; d = i16(g, p + 2) / 16384; p += 4; }
    else if (flags & 0x0100) { a = i16(g, p) / 16384; b2 = i16(g, p + 2) / 16384; c2 = i16(g, p + 4) / 16384; d = i16(g, p + 6) / 16384; p += 8; }
    const dx = (flags & 0x0002) ? arg1 : 0; const dy = (flags & 0x0002) ? arg2 : 0;
    for (const cont of glyphContours(f, comp, depth + 1)) {
      out.push(cont.map((pt) => ({ x: a * pt.x + c2 * pt.y + dx, y: b2 * pt.x + d * pt.y + dy, on: pt.on })));
    }
    if (!(flags & 0x0020)) break;
  }
  return out;
}

// ---------- glyph rasterisation (2x supersample, even-odd fill) ----------
type GlyphBmp = { w: number; h: number; bmp: Uint8Array; adv: number; bx: number; by: number };
const glyphCache = new Map<string, GlyphBmp>();
function rasterGlyph(font: Font, code: number, px: number, italic: boolean): GlyphBmp {
  const key = (font === SERIF ? "S" : font === SANS ? "R" : "B") + "|" + code + "|" + px + "|" + (italic ? 1 : 0);
  const hit = glyphCache.get(key);
  if (hit) return hit;
  const gid = font.cmap.get(code) ?? 0;
  const adv = advanceOf(font, gid) / font.upm * px;
  const contours = glyphContours(font, gid, 0);
  const empty: GlyphBmp = { w: 0, h: 0, bmp: new Uint8Array(0), adv, bx: 0, by: 0 };
  if (contours.length === 0) { glyphCache.set(key, empty); return empty; }
  const sc = px / font.upm;
  const shear = italic ? 0.18 : 0;
  // flatten to line segments in pixel space (y down, origin at baseline)
  type Seg = { x0: number; y0: number; x1: number; y1: number };
  const segs: Seg[] = [];
  let minX = 1e9; let maxX = -1e9; let minY = 1e9; let maxY = -1e9;
  const pushPt = (x: number, y: number) => { if (x < minX) minX = x; if (x > maxX) maxX = x; if (y < minY) minY = y; if (y > maxY) maxY = y; };
  for (const cont of contours) {
    if (cont.length === 0) continue;
    // expand contour into on-curve point list (implied midpoints)
    const pts: { x: number; y: number }[] = [];
    const n = cont.length;
    for (let i = 0; i < n; i++) {
      const cur = cont[i]; const nxt = cont[(i + 1) % n];
      if (cur.on) pts.push({ x: cur.x, y: cur.y });
      else {
        if (nxt.on) pts.push({ x: cur.x, y: cur.y });
        else pts.push({ x: (cur.x + nxt.x) / 2, y: (cur.y + nxt.y) / 2 });
      }
    }
    if (pts.length < 2) continue;
    // walk: segments between consecutive on-curve points, quadratic if an off-curve sits between
    let prev = pts[pts.length - 1];
    let prevOff: { x: number; y: number } | null = null;
    // find off-curve points: rebuild walk with original flags
    const seq: { p: { x: number; y: number }; off: boolean }[] = [];
    for (let i = 0; i < n; i++) {
      const cur = cont[i];
      seq.push({ p: { x: cur.x, y: cur.y }, off: !cur.on });
    }
    // convert seq to drawing steps
    let cur2 = seq[seq.length - 1];
    let startP = { x: 0, y: 0 }; let haveStart = false;
    // find first on-curve as start
    let si = 0; while (si < n && seq[si].off) si++;
    if (si >= n) continue;
    startP = seq[si].p; haveStart = true;
    let pen = startP;
    for (let k = 1; k <= n; k++) {
      const it = seq[(si + k) % n];
      const nxt2 = seq[(si + k + 1) % n];
      if (!it.off) {
        const a = { x: pen.x * sc, y: -pen.y * sc }; const b = { x: it.p.x * sc, y: -it.p.y * sc };
        segs.push({ x0: a.x, y0: a.y, x1: b.x, y1: b.y }); pushPt(a.x, a.y); pushPt(b.x, b.y);
        pen = it.p;
      } else {
        const endP = nxt2.off ? { x: (it.p.x + nxt2.p.x) / 2, y: (it.p.y + nxt2.p.y) / 2 } : nxt2.p;
        const P0 = { x: pen.x * sc, y: -pen.y * sc };
        const P1 = { x: it.p.x * sc, y: -it.p.y * sc };
        const P2 = { x: endP.x * sc, y: -endP.y * sc };
        const STEPS = 10;
        let px0 = P0.x; let py0 = P0.y;
        for (let s = 1; s <= STEPS; s++) {
          const t = s / STEPS; const mt = 1 - t;
          const qx = mt * mt * P0.x + 2 * mt * t * P1.x + t * t * P2.x;
          const qy = mt * mt * P0.y + 2 * mt * t * P1.y + t * t * P2.y;
          segs.push({ x0: px0, y0: py0, x1: qx, y1: qy }); pushPt(qx, qy);
          px0 = qx; py0 = qy;
        }
        pen = endP;
      }
    }
    void prev; void prevOff; void cur2; void haveStart;
  }
  if (segs.length === 0) { glyphCache.set(key, empty); return empty; }
  const SS = 2;
  const ox = Math.floor(minX) - 1; const oy = Math.floor(minY) - 1;
  const w = Math.ceil(maxX - ox) + 2; const h = Math.ceil(maxY - oy) + 2;
  // Fractional coverage fill: a thin stem (~1.4px at 9.5px type) can fall between
  // subpixel grid lines, so ceil/floor dropped it entirely (lost i/l/r/p).
  // Accumulate the covered fraction of every subpixel instead.
  const big = new Float32Array(w * SS * h * SS);
  for (let row = 0; row < h * SS; row++) {
    const y = oy + (row + 0.5) / SS;
    const xs: number[] = [];
    for (const s of segs) {
      if ((s.y0 <= y && s.y1 > y) || (s.y1 <= y && s.y0 > y)) {
        const t = (y - s.y0) / (s.y1 - s.y0);
        xs.push(s.x0 + t * (s.x1 - s.x0));
      }
    }
    xs.sort((a, b) => a - b);
    for (let i = 0; i + 1 < xs.length; i += 2) {
      const X0 = (xs[i] - ox) * SS; const X1 = (xs[i + 1] - ox) * SS;
      const xa = Math.max(0, Math.floor(X0));
      const xb = Math.min(w * SS - 1, Math.floor(X1 - 1e-9));
      for (let xx = xa; xx <= xb; xx++) {
        const cov = Math.min(xx + 1, X1) - Math.max(xx, X0);
        if (cov > 0) { const idx = row * w * SS + xx; big[idx] = Math.min(1, big[idx] + cov); }
      }
    }
  }
  // downsample 2x2 (coverage 0..1 per subpixel -> alpha 0..255)
  const bmp = new Uint8Array(w * h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    let s = 0;
    for (let dy = 0; dy < SS; dy++) for (let dx = 0; dx < SS; dx++) s += big[(y * SS + dy) * w * SS + x * SS + dx];
    bmp[y * w + x] = Math.round(s / (SS * SS) * 255);
  }
  const res: GlyphBmp = { w, h, bmp, adv, bx: ox, by: oy };
  void shear;
  glyphCache.set(key, res);
  return res;
}

