const W = 1024; const H = 1024;
const img = new Uint8Array(W * H * 3);
type RGB = [number, number, number];
const CREAM: RGB = [247, 243, 232]; const INK: RGB = [20, 20, 20]; const RED: RGB = [185, 28, 28];
const GREY: RGB = [90, 86, 78]; const WHITE: RGB = [255, 255, 255]; const PAPER: RGB = [255, 253, 247];
function fillAll(c: RGB): void { for (let i = 0; i < W * H; i++) { img[i * 3] = c[0]; img[i * 3 + 1] = c[1]; img[i * 3 + 2] = c[2]; } }
function px(x: number, y: number, c: RGB, a: number): void {
  const xi = Math.round(x); const yi = Math.round(y);
  if (xi < 0 || yi < 0 || xi >= W || yi >= H) return;
  const i = (yi * W + xi) * 3;
  if (a >= 255) { img[i] = c[0]; img[i + 1] = c[1]; img[i + 2] = c[2]; return; }
  img[i] = Math.round(img[i] * (1 - a / 255) + c[0] * (a / 255));
  img[i + 1] = Math.round(img[i + 1] * (1 - a / 255) + c[1] * (a / 255));
  img[i + 2] = Math.round(img[i + 2] * (1 - a / 255) + c[2] * (a / 255));
}
function rect(x: number, y: number, w: number, h: number, c: RGB, a = 255): void {
  const x0 = Math.max(0, Math.floor(x)); const y0 = Math.max(0, Math.floor(y));
  const x1 = Math.min(W, Math.ceil(x + w)); const y1 = Math.min(H, Math.ceil(y + h));
  for (let yy = y0; yy < y1; yy++) for (let xx = x0; xx < x1; xx++) px(xx, yy, c, a);
}
function hline(x: number, y: number, w: number, c: RGB, th = 1): void { rect(x, y, w, th, c); }
function vline(x: number, y: number, h: number, c: RGB, th = 1): void { rect(x, y, th, h, c); }
function frame(x: number, y: number, w: number, h: number, c: RGB, th = 1): void {
  hline(x, y, w, c, th); hline(x, y + h - th, w, c, th); vline(x, y, h, c, th); vline(x + w - th, y, h, c, th);
}
function circle(cx: number, cy: number, r: number, c: RGB, a = 255): void {
  for (let y = Math.floor(cy - r); y <= Math.ceil(cy + r); y++)
    for (let x = Math.floor(cx - r); x <= Math.ceil(cx + r); x++) {
      const dx = x + 0.5 - cx; const dy = y + 0.5 - cy;
      if (dx * dx + dy * dy <= r * r) px(x, y, c, a);
    }
}
function ring(cx: number, cy: number, r: number, c: RGB, th = 2): void {
  for (let y = Math.floor(cy - r - 1); y <= Math.ceil(cy + r + 1); y++)
    for (let x = Math.floor(cx - r - 1); x <= Math.ceil(cx + r + 1); x++) {
      const dx = x + 0.5 - cx; const dy = y + 0.5 - cy; const d = Math.sqrt(dx * dx + dy * dy);
      if (d <= r && d >= r - th) px(x, y, c);
    }
}
function poly(pts: [number, number][], c: RGB, a = 255): void {
  if (pts.length < 3) return;
  let minY = 1e9; let maxY = -1e9;
  for (const p of pts) { if (p[1] < minY) minY = p[1]; if (p[1] > maxY) maxY = p[1]; }
  for (let y = Math.floor(minY); y <= Math.ceil(maxY); y++) {
    const xs: number[] = [];
    for (let i = 0; i < pts.length; i++) {
      const a1 = pts[i]; const b1 = pts[(i + 1) % pts.length];
      if ((a1[1] <= y + 0.5 && b1[1] > y + 0.5) || (b1[1] <= y + 0.5 && a1[1] > y + 0.5)) {
        const t = (y + 0.5 - a1[1]) / (b1[1] - a1[1]);
        xs.push(a1[0] + t * (b1[0] - a1[0]));
      }
    }
    xs.sort((p, q) => p - q);
    for (let i = 0; i + 1 < xs.length; i += 2)
      for (let x = Math.ceil(xs[i]); x < xs[i + 1]; x++) px(x, y, c, a);
  }
}
function thickLine(x0: number, y0: number, x1: number, y1: number, th: number, c: RGB): void {
  const dx = x1 - x0; const dy = y1 - y0; const len = Math.hypot(dx, dy) || 1;
  const nx = (-dy / len) * th / 2; const ny = (dx / len) * th / 2;
  poly([[x0 + nx, y0 + ny], [x1 + nx, y1 + ny], [x1 - nx, y1 - ny], [x0 - nx, y0 - ny]], c);
}
function rrect(x: number, y: number, w: number, h: number, r: number, c: RGB): void {
  rect(x + r, y, w - 2 * r, h, c); rect(x, y + r, w, h - 2 * r, c);
  circle(x + r, y + r, r, c); circle(x + w - r, y + r, r, c);
  circle(x + r, y + h - r, r, c); circle(x + w - r, y + h - r, r, c);
}
function star(cx: number, cy: number, r: number, c: RGB): void {
  const pts: [number, number][] = [];
  for (let i = 0; i < 10; i++) {
    const ang = -Math.PI / 2 + i * Math.PI / 5;
    const rr = i % 2 === 0 ? r : r * 0.45;
    pts.push([cx + Math.cos(ang) * rr, cy + Math.sin(ang) * rr]);
  }
  poly(pts, c);
}

