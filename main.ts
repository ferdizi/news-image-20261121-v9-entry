type FontKind = "serif" | "sans" | "sansb";
function fontOf(k: FontKind): Font { return k === "serif" ? SERIF : k === "sans" ? SANS : SANSB; }
function textWidth(s: string, k: FontKind, pxSize: number, tracking = 0): number {
  const f = fontOf(k); let w = 0;
  for (const ch of s) {
    const code = ch.codePointAt(0)!;
    const gid = f.cmap.get(code) ?? 0;
    w += advanceOf(f, gid) / f.upm * pxSize + tracking;
  }
  return w - (s.length ? tracking : 0);
}
function drawText(x: number, yBase: number, s: string, k: FontKind, pxSize: number, c: RGB, o: { tracking?: number; italic?: boolean } = {}): number {
  const f = fontOf(k); const tr = o.tracking ?? 0; const it = o.italic ?? false;
  let cx = x;
  for (const ch of s) {
    const code = ch.codePointAt(0)!;
    const g = rasterGlyph(f, code, pxSize, it);
    // italic shear at blit: shift each row right as it goes up
    for (let gy = 0; gy < g.h; gy++) {
      const shift = it ? Math.round((g.h - gy) * 0.16) : 0;
      for (let gx = 0; gx < g.w; gx++) {
        const a = g.bmp[gy * g.w + gx];
        if (a) px(cx + g.bx + gx + shift, yBase + g.by + gy, c, a);
      }
    }
    cx += g.adv + tr;
  }
  return cx - x - (s.length ? tr : 0);
}
